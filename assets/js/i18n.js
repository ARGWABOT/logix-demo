/* ---- API mínima ---- */
window.LANG = 'en';
window.t = function(key, vars){
  var dict = window.I18N[window.LANG] || window.I18N.en;
  var s = dict[key];
  if (s === undefined) s = (window.I18N.en[key] !== undefined ? window.I18N.en[key] : key);
  if (vars) for (var k in vars) s = s.split('{'+k+'}').join(vars[k]);
  return s;
};
